def delete_child(user_id: int) -> bool:
    conn = get_db()
    cur = conn.execute(
        "DELETE FROM users WHERE id = %s AND role = 'kind'", (user_id,)
    )
    conn.commit()
    return cur.rowcount == 1


def add_attempt(user_id: int, grade: int, mode: str, correct: bool) -> None:
    got = 1 if correct else 0
    missed = 0 if correct else 1
    conn = get_db()
    conn.execute(
        """
        INSERT INTO progress (user_id, grade, mode, correct, wrong)
        VALUES (%s, %s, %s, %s, %s)
        ON CONFLICT (user_id, grade, mode) DO UPDATE SET
            correct = progress.correct + EXCLUDED.correct,
            wrong = progress.wrong + EXCLUDED.wrong
        """,
        (user_id, grade, mode, got, missed),
    )
    conn.commit()


