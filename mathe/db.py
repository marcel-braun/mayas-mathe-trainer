class DuplicateUser(Exception):
    pass


def utcnow() -> datetime:
    return datetime.now(timezone.utc)


def _convert(value):
    if isinstance(value, tuple):
        return list(value)
    raise TypeError(f"nicht speicherbar: {type(value)!r}")


def _dumps(data) -> str:
    return json.dumps(data, ensure_ascii=False, default=_convert)


def _jsonb(data):
    return Jsonb(data, dumps=_dumps)


def pg_settings() -> dict:
    missing = [name for name in PG_ENV if not os.environ.get(name)]
    if missing:
        names = ", ".join(missing)
        raise RuntimeError(f"Datenbank-Variablen fehlen: {names}")
    return {
        "host": os.environ["PGHOST"],
        "port": int(os.environ["PGPORT"]),
        "user": os.environ["PGUSER"],
        "password": os.environ["PGPASSWORD"],
        "dbname": os.environ["PGDATABASE"],
    }


def connect(retries: int = 1) -> psycopg.Connection:
    settings = pg_settings()
    last = None
    for attempt in range(retries):
        try:
            return psycopg.connect(row_factory=dict_row, connect_timeout=5, **settings)
        except psycopg.OperationalError as exc:
            last = exc
            if attempt + 1 < retries:
                time.sleep(1)
    raise last


def init_db() -> None:
    conn = connect(retries=30)
    try:
        with conn.transaction():
            for statement in STATEMENTS:
                conn.execute(statement)
            conn.execute("LOCK TABLE users IN EXCLUSIVE MODE")
            count = conn.execute("SELECT COUNT(*) AS n FROM users").fetchone()["n"]
            if count == 0:
                moment = utcnow()
                conn.execute(
                    """
                    INSERT INTO users
                        (username, display_name, password_hash, role, created_at)
                    VALUES (%s, %s, %s, 'admin', %s)
                    """,
                    ("admin", "Admin", hash_password("admin"), moment),
                )
                conn.execute(
                    """
                    INSERT INTO users
                        (username, display_name, password_hash, role, created_at)
                    VALUES (%s, %s, %s, 'kind', %s)
                    """,
                    ("maya", "Maya", hash_password("maya"), moment),
                )
                print("Standardnutzer admin und maya wurden angelegt.", flush=True)
            conn.execute(
                "DELETE FROM sessions WHERE expires_at <= %s",
                (utcnow(),),
            )
    finally:
        conn.close()


def ensure_init() -> None:
    global _ready
    if _ready:
        return
    with _lock:
        if _ready:
            return
        init_db()
        _ready = True


def secret_key() -> bytes:
    base = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    path = os.environ.get("MATHE_SECRET_PATH", os.path.join(base, "data", "secret.key"))
    folder = os.path.dirname(path) or "."
    os.makedirs(folder, exist_ok=True)
    if not os.path.exists(path):
        with open(path, "wb") as handle:
            handle.write(os.urandom(32))
    with open(path, "rb") as handle:
        return handle.read()


def get_db() -> psycopg.Connection:
    if "db" not in g:
        g.db = connect(retries=3)
    return g.db


def close_db(_exc=None) -> None:
    conn = g.pop("db", None)
    if conn is not None:
        conn.close()


def _user(row) -> dict | None:
    return dict(row) if row else None


def user_by_id(user_id: int) -> dict | None:
    row = get_db().execute(
        "SELECT * FROM users WHERE id = %s", (user_id,)
    ).fetchone()
    return _user(row)


def user_by_username(username: str) -> dict | None:
    row = get_db().execute(
        "SELECT * FROM users WHERE username = %s", (username,)
    ).fetchone()
    return _user(row)


def list_users() -> list[dict]:
    rows = get_db().execute(
        """
        SELECT * FROM users
        ORDER BY CASE role WHEN 'admin' THEN 0 ELSE 1 END,
                 lower(display_name),
                 id
        """
    ).fetchall()
    return [dict(row) for row in rows]


def create_child(username: str, display_name: str, password: str) -> int:
    conn = get_db()
    try:
        row = conn.execute(
            """
            INSERT INTO users (username, display_name, password_hash, role, created_at)
            VALUES (%s, %s, %s, 'kind', %s)
            RETURNING id
            """,
            (username, display_name, hash_password(password), utcnow()),
        ).fetchone()
        conn.commit()
    except psycopg.errors.UniqueViolation:
        conn.rollback()
        raise DuplicateUser
    return int(row["id"])


def update_user(
    user_id: int,
    *,
    display_name: str,
    username: str | None = None,
    password: str | None = None,
) -> None:
    conn = get_db()
    try:
        if username is None:
            conn.execute(
                "UPDATE users SET display_name = %s WHERE id = %s",
                (display_name, user_id),
            )
        else:
            conn.execute(
                "UPDATE users SET display_name = %s, username = %s WHERE id = %s",
                (display_name, username, user_id),
            )
        if password:
            conn.execute(
                "UPDATE users SET password_hash = %s WHERE id = %s",
                (hash_password(password), user_id),
            )
        conn.commit()
    except psycopg.errors.UniqueViolation:
        conn.rollback()
        raise DuplicateUser


