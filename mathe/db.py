def progress_overview() -> list[dict]:
    users = list_users()
    rows = get_db().execute(
        "SELECT user_id, grade, mode, correct, wrong FROM progress"
    ).fetchall()
    by_user: dict[int, list[dict]] = {user["id"]: [] for user in users}
    for row in rows:
        by_user.setdefault(row["user_id"], []).append(dict(row))
    overview = []
    for user in users:
        overview.append({"user": user, "rows": by_user.get(user["id"], [])})
    return overview


def skill_stats_for(user_id: int, grade: int, mode: str) -> list[dict]:
    rows = get_db().execute(
        """
        SELECT skill, correct, wrong, last_wrong_at, last_correct_at
        FROM skill_stats
        WHERE user_id = %s AND grade = %s AND mode = %s
        """,
        (user_id, grade, mode),
    ).fetchall()
    return [dict(row) for row in rows]


def open_mistakes(user_id: int, grade: int, mode: str) -> list[dict]:
    rows = get_db().execute(
        """
        SELECT signature, snapshot, created_at
        FROM mistakes
        WHERE user_id = %s AND grade = %s AND mode = %s AND resolved_at IS NULL
        ORDER BY created_at DESC
        LIMIT 8
        """,
        (user_id, grade, mode),
    ).fetchall()
    found = []
    for row in rows:
        item = dict(row)
        if isinstance(item["snapshot"], str):
            item["snapshot"] = json.loads(item["snapshot"])
        found.append(item)
    return found


def record_outcome(user_id: int, task: dict, correct: bool) -> None:
    from mathe.tasks import task_signature, task_type_key

    grade = int(task["grade"])
    mode = task["mode"]
    skill = task_type_key(task)
    signature = task_signature(task)
    prompt = " ".join((task.get("prompt") or "").split())[:180]
    snapshot = dict(task)
    snapshot.pop("noted", None)
    got = 1 if correct else 0
    missed = 0 if correct else 1
    moment = utcnow()
    conn = get_db()
    conn.execute(
        """
        INSERT INTO progress (user_id, grade, mode, correct, wrong)
        VALUES (%s, %s, %s, %s, %s)
        ON CONFLICT (user_id, grade, mode) DO UPDATE SET
            correct = progress.correct + EXCLUDED.correct,
            wrong = progress.wrong + EXCLUDED.wrong
        """,
        (user_id, grade, mode, got, missed),
    )
    conn.execute(
        """
        INSERT INTO skill_stats
            (user_id, grade, mode, skill, correct, wrong, last_wrong_at, last_correct_at)
        VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
        ON CONFLICT (user_id, grade, mode, skill) DO UPDATE SET
            correct = skill_stats.correct + EXCLUDED.correct,
            wrong = skill_stats.wrong + EXCLUDED.wrong,
            last_wrong_at = CASE
                WHEN EXCLUDED.wrong > 0 THEN EXCLUDED.last_wrong_at
                ELSE skill_stats.last_wrong_at END,
            last_correct_at = CASE
                WHEN EXCLUDED.correct > 0 THEN EXCLUDED.last_correct_at
                ELSE skill_stats.last_correct_at END
        """,
        (
            user_id,
            grade,
            mode,
            skill,
            got,
            missed,
            moment if missed else None,
            moment if got else None,
        ),
    )
    if correct:
        conn.execute(
            """
            UPDATE mistakes
            SET resolved_at = %s
            WHERE user_id = %s AND grade = %s AND mode = %s
              AND signature = %s AND resolved_at IS NULL
            """,
            (moment, user_id, grade, mode, signature),
        )
    else:
        existing = conn.execute(
            """
            SELECT id FROM mistakes
            WHERE user_id = %s AND grade = %s AND mode = %s
              AND signature = %s AND resolved_at IS NULL
            ORDER BY created_at DESC
            LIMIT 1
            """,
            (user_id, grade, mode, signature),
        ).fetchone()
        if existing:
            conn.execute(
                """
                UPDATE mistakes
                SET created_at = %s, prompt = %s, snapshot = %s
                WHERE id = %s
                """,
                (moment, prompt, _jsonb(snapshot), existing["id"]),
            )
        else:
            conn.execute(
                """
                INSERT INTO mistakes
                    (user_id, grade, mode, skill, signature, prompt, snapshot, created_at)
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
                """,
                (user_id, grade, mode, skill, signature, prompt, _jsonb(snapshot), moment),
            )
    conn.commit()


def skill_overview() -> list[dict]:
    users = list_users()
    stats = get_db().execute(
        """
        SELECT user_id, grade, mode, skill, correct, wrong
        FROM skill_stats
        ORDER BY grade, mode, skill
        """
    ).fetchall()
    misses = get_db().execute(
        """
        SELECT user_id, grade, mode, skill, prompt, created_at, resolved_at
        FROM mistakes
        ORDER BY created_at DESC
        LIMIT 40
        """
    ).fetchall()
    by_stats: dict[int, list[dict]] = {user["id"]: [] for user in users}
    by_miss: dict[int, list[dict]] = {user["id"]: [] for user in users}
    for row in stats:
        by_stats.setdefault(row["user_id"], []).append(dict(row))
    for row in misses:
        bucket = by_miss.setdefault(row["user_id"], [])
        if len(bucket) < 8:
            bucket.append(dict(row))
    return [
        {"user": user, "stats": by_stats.get(user["id"], []), "mistakes": by_miss.get(user["id"], [])}
        for user in users
    ]


def create_session(user_id: int, data: dict) -> str:
    sid = secrets.token_urlsafe(32)
    expires = utcnow() + timedelta(days=SESSION_DAYS)
    conn = get_db()
    conn.execute("DELETE FROM sessions WHERE expires_at <= %s", (utcnow(),))
    conn.execute(
        """
        INSERT INTO sessions (id, user_id, data, expires_at)
        VALUES (%s, %s, %s, %s)
        """,
        (sid, user_id, _jsonb(data), expires),
    )
    conn.commit()
    return sid


def read_session(sid: str) -> dict | None:
    if not sid:
        return None
    row = get_db().execute(
        "SELECT * FROM sessions WHERE id = %s", (sid,)
    ).fetchone()
    if row is None:
        return None
    if row["expires_at"] <= utcnow():
        delete_session(sid)
        return None
    data = row["data"]
    if isinstance(data, str):
        data = json.loads(data)
    return {
        "id": row["id"],
        "user_id": row["user_id"],
        "data": data,
        "expires_at": row["expires_at"],
    }


def write_session(sid: str, data: dict) -> None:
    expires = utcnow() + timedelta(days=SESSION_DAYS)
    conn = get_db()
    conn.execute(
        "UPDATE sessions SET data = %s, expires_at = %s WHERE id = %s",
        (_jsonb(data), expires, sid),
    )
    conn.commit()


def delete_session(sid: str) -> None:
    conn = get_db()
    conn.execute("DELETE FROM sessions WHERE id = %s", (sid,))
    conn.commit()
